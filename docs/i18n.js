const INIT = (() => {
  try {
    const opgeslagen = localStorage.getItem('jm-orgue-site-lang');
    if (opgeslagen && DICT[opgeslagen]) return opgeslagen;
  } catch (e) {}
  const bro = (navigator.language || 'nl').toLowerCase().slice(0, 2);
  return DICT[bro] ? bro : 'nl';
})();

function zetTaal(l) {
  const dict = DICT[l] || DICT.nl;
  document.documentElement.lang = l;
  document.title = 'JM-Orgue — ' + dict.tagline;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const sl = el.getAttribute('data-i18n');
    if (dict[sl] !== undefined) el.innerHTML = dict[sl];
  });
  document.querySelectorAll('.langbar button').forEach((b) => {
    b.classList.toggle('active', b.getAttribute('data-lang') === l);
  });
  try { localStorage.setItem('jm-orgue-site-lang', l); } catch (e) {}
}

document.querySelectorAll('.langbar button').forEach((b) => {
  b.addEventListener('click', () => zetTaal(b.getAttribute('data-lang')));
});
zetTaal(INIT);
